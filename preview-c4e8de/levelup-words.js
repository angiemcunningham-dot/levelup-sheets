  function fill(tpl, vars) {
    if (tpl == null) return null;
    return String(tpl).replace(/\{([A-Z_]+)\}/g, function (m, k) {
      var v = vars && vars[k];
      return (v === null || v === undefined) ? '' : String(v);
    });
  }

