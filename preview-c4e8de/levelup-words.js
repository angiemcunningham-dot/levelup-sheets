  /* A string substitution and nothing more: {NAME} is replaced by vars.NAME, and an unsupplied name
     becomes empty rather than appearing on a member's screen as a brace. */
  function fill(tpl, vars) {
    if (tpl == null) return null;
    return String(tpl).replace(/\{([A-Z_]+)\}/g, function (m, k) {
      var v = vars && vars[k];
      return (v === null || v === undefined) ? '' : String(v);
    });
  }

  /* Every string in the table that is still a placeholder, so a test can assert the list has not
     silently grown and a reviewer can see at a glance what is still waiting on Chelsea. */
